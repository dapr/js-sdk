import { Code, ConnectError } from "@connectrpc/connect";
import { create } from "@bufbuild/protobuf";
import {
  BinaryStoreWorkflowPayloadResolver,
  DaprWorkflowClient,
  PayloadReference,
  PayloadWritePreference,
  PayloadRehydrationLimitError,
  PayloadNotFoundError,
  PayloadKind,
} from "../../../src";
import { GetInstanceResponseSchema } from "../../../src/proto/dapr/proto/durabletask/v1/orchestrator_service_pb";
import {
  OrchestrationStatus,
  WorkflowStateSchema,
} from "../../../src/proto/dapr/proto/durabletask/v1/orchestration_pb";
import { MemoryPayloadStore } from "../../utils/WorkflowPayloadTestUtils";

const mockRpc = {
  startInstance: jest.fn(),
  raiseEvent: jest.fn(),
  terminateInstance: jest.fn(),
  rerunWorkflowFromEvent: jest.fn(),
  getInstance: jest.fn(),
  waitForInstanceStart: jest.fn(),
  waitForInstanceCompletion: jest.fn(),
  purgeInstances: jest.fn(),
  getInstanceHistory: jest.fn(),
};

jest.mock("@connectrpc/connect", () => ({
  ...jest.requireActual("@connectrpc/connect"),
  createClient: () => mockRpc,
}));

describe("workflow client data references", () => {
  let store: MemoryPayloadStore;
  let payloads: BinaryStoreWorkflowPayloadResolver;
  let client: DaprWorkflowClient;

  beforeEach(() => {
    jest.resetAllMocks();
    store = new MemoryPayloadStore();
    payloads = new BinaryStoreWorkflowPayloadResolver(store, {
      storeName: "store",
      writePreference: PayloadWritePreference.PreferReference,
      offloadThreshold: 1,
    });
    client = new DaprWorkflowClient({ payloads });
    mockRpc.startInstance.mockImplementation(async (request) => ({ instanceId: request.instanceId }));
    mockRpc.rerunWorkflowFromEvent.mockImplementation(async (request) => ({ newInstanceID: request.newInstanceID }));
  });

  it("writes before scheduling and scopes autogenerated instance IDs into content keys", async () => {
    const data = { value: "large" };
    mockRpc.startInstance.mockImplementation(async (request) => {
      const ref = PayloadReference.parse(request.input)!;
      expect(store.files.has(`${ref.storeName}/${ref.key}`)).toBe(true);
      expect(ref.key).toContain(`/${request.instanceId}/`);
      return { instanceId: request.instanceId };
    });
    const id = await client.scheduleNewWorkflow("workflow", data);
    expect(id).toBeTruthy();
    expect(await payloads.resolve(PayloadReference.parse(mockRpc.startInstance.mock.calls[0][0].input)!)).toEqual(data);
  });

  it("preserves explicit reference envelopes without reserializing or uploading them again", async () => {
    const reference = await payloads.store({ value: 1 }, "source");
    const writes = store.writes;
    await client.scheduleNewWorkflow("workflow", reference, "target");
    expect(mockRpc.startInstance.mock.calls[0][0].input).toBe(reference.toEnvelope());
    expect(store.writes).toBe(writes);
  });

  it("honors event and termination write sites, and forwards cancellation signals", async () => {
    const controller = new AbortController();
    await client.raiseEvent("target", "event", { value: 1 }, controller.signal);
    await client.terminateWorkflow("target", { value: 2 }, controller.signal);
    expect(PayloadReference.parse(mockRpc.raiseEvent.mock.calls[0][0].input)?.key).toContain("/target/");
    expect(PayloadReference.parse(mockRpc.terminateInstance.mock.calls[0][0].output)?.key).toContain("/target/");
    expect(mockRpc.raiseEvent.mock.calls[0][1].signal).toBe(controller.signal);
    const eventOnly = new BinaryStoreWorkflowPayloadResolver(store, {
      storeName: "store",
      writePreference: PayloadWritePreference.PreferReference,
      offloadThreshold: null,
      offloadSites: PayloadKind.ExternalEvent,
    });
    await new DaprWorkflowClient({ payloads: eventOnly }).terminateWorkflow("target", 1);
    expect(mockRpc.terminateInstance.mock.calls[1][0].output).toBe("1");
  });

  it("assigns rerun replacement payloads to the new instance", async () => {
    const id = await client.rerunWorkflowFromEvent("source", 7, { input: { value: 1 } });
    const request = mockRpc.rerunWorkflowFromEvent.mock.calls[0][0];
    expect(id).toBeTruthy();
    expect(id).not.toBe("source");
    expect(PayloadReference.parse(request.input)?.key).toContain(`/${id}/`);
  });

  it("does not upload ignored rerun replacement input", async () => {
    await client.rerunWorkflowFromEvent("source", 7, { input: { value: 1 }, overwriteInput: false });
    const request = mockRpc.rerunWorkflowFromEvent.mock.calls[0][0];
    expect(request.overwriteInput).toBe(false);
    expect(request.newInstanceID).toBeUndefined();
    expect(store.writes).toBe(0);
  });

  it("does not invoke the workflow RPC if upload fails or the caller is already canceled", async () => {
    const error = new ConnectError("offline", Code.Unavailable);
    jest.spyOn(store, "setBinaryFile").mockRejectedValue(error);
    await expect(client.scheduleNewWorkflow("workflow", { data: 1 })).rejects.toBe(error);
    expect(mockRpc.startInstance).not.toHaveBeenCalled();
    const controller = new AbortController();
    controller.abort();
    await expect(client.scheduleNewWorkflow("workflow", {}, "id", undefined, controller.signal)).rejects.toMatchObject({
      code: Code.Canceled,
    });
    expect(store.setBinaryFile).toHaveBeenCalledTimes(1);
  });

  it.each(["get", "start", "complete"] as const)("prepares synchronous state readers for %s", async (operation) => {
    const reference = await payloads.store({ value: 1 }, "id");
    const response = create(GetInstanceResponseSchema, {
      exists: true,
      workflowState: create(WorkflowStateSchema, {
        name: "workflow",
        workflowStatus: OrchestrationStatus.COMPLETED,
        input: reference.toEnvelope(),
        output: reference.toEnvelope(),
        customStatus: reference.toEnvelope(),
      }),
    });
    mockRpc.getInstance.mockResolvedValue(response);
    mockRpc.waitForInstanceStart.mockResolvedValue(response);
    mockRpc.waitForInstanceCompletion.mockResolvedValue(response);
    const state =
      operation === "get"
        ? await client.getWorkflowState("id", true)
        : operation === "start"
        ? await client.waitForWorkflowStart("id")
        : await client.waitForWorkflowCompletion("id");
    expect(state?.getInput()).toEqual({ value: 1 });
    expect(state?.getOutput()).toEqual({ value: 1 });
    expect(state?.getCustomStatus()).toEqual({ value: 1 });
    expect(state?.serializedOutput).toBe('{"value":1}');
    expect(state?.getInputReference()).toEqual(reference);
    expect(state?.getOutputReference()).toEqual(reference);
    expect(state?.getCustomStatusReference()).toEqual(reference);
  });

  it("keeps oversized references accessible while refusing buffered access", async () => {
    const reference = await payloads.store({ text: "x".repeat(100) }, "id");
    const limited = new BinaryStoreWorkflowPayloadResolver(store, {
      storeName: "store",
      maxInMemoryRehydrationSize: 1,
    });
    mockRpc.getInstance.mockResolvedValue(
      create(GetInstanceResponseSchema, {
        exists: true,
        workflowState: { output: reference.toEnvelope() },
      }),
    );
    const state = await new DaprWorkflowClient({ payloads: limited }).getWorkflowState("id", true);
    expect(state?.getOutputReference()).toEqual(reference);
    expect(() => state?.getOutput()).toThrow(PayloadRehydrationLimitError);
    expect(store.reads).toBe(0);
  });

  it("does not misreport a missing binary payload as a missing workflow", async () => {
    const reference = await payloads.store({ value: 1 }, "id");
    store.files.clear();
    mockRpc.getInstance.mockResolvedValue(
      create(GetInstanceResponseSchema, {
        exists: true,
        workflowState: { output: reference.toEnvelope() },
      }),
    );
    await expect(client.getWorkflowState("id", true)).rejects.toBeInstanceOf(PayloadNotFoundError);
  });

  it("does not read payloads for metadata-only results or purge binary-store objects", async () => {
    const reference = await payloads.store({ value: 1 }, "id");
    mockRpc.getInstance.mockResolvedValue(
      create(GetInstanceResponseSchema, { exists: true, workflowState: { name: "workflow" } }),
    );
    await client.getWorkflowState("id", false);
    expect(store.reads).toBe(0);
    mockRpc.purgeInstances.mockResolvedValue({ deletedInstanceCount: 1 });
    expect(await client.purgeWorkflow("id")).toBe(true);
    expect(store.files.has(`${reference.storeName}/${reference.key}`)).toBe(true);
  });
});
